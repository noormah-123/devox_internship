# Distance Converter
def kilometer_to_miles(km):
    return km *  0.621371
def miles_to_kilometers(miles):
    return miles * 1.60934
def meter_to_kilometer(meter):
    return meter * 0.001
print("Distance Converter:")
print("25km =", kilometer_to_miles(25),"miles")
print("4 miles =", miles_to_kilometers(4),"km")
print("100m =", meter_to_kilometer(100),"km")
